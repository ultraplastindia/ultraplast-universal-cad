/* Automatic dimension fields. The studio reads the drawing and lists the sizes an engineer would want to change
 * (overall length/width, hole diameters, pitch circle, number of holes, thickness, every driving dimension, every feature value).
 * Changing a field changes the drawing; changing the drawing changes the field. */

export type ParamUnit = 'mm' | 'deg' | 'count' | 'factor';
export interface Param {
  id: string; group: string; label: string; unit: ParamUnit; value: number; min: number; max: number;
  /** where the number comes from */
  origin: 'measured' | 'dimension' | 'feature' | 'body' | 'library';
  /** entities to highlight when the field is focused */
  ents: string[];
  hint?: string;
}
export type ApplyResult = { ok: true; doc: StudioDoc; note?: string } | { ok: false; error: string };

const r6 = (v: number) => Math.round(v * 1e6) / 1e6;
function outerLoops(d: StudioDoc): { outer: Loop; holes: Loop[] }[] {
  const { loops } = findLoops(d);
  const outers = loops.filter((l) => !loops.some((o) => o !== l && loopInside(l, o)));
  return outers.map((o) => ({ outer: o, holes: loops.filter((l) => l !== o && loopInside(l, o)) }));
}
const loopBox = (l: Loop) => l.pts.reduce((b, p) => ({ x0: Math.min(b.x0, p[0]), y0: Math.min(b.y0, p[1]), x1: Math.max(b.x1, p[0]), y1: Math.max(b.y1, p[1]) }), { x0: Infinity, y0: Infinity, x1: -Infinity, y1: -Infinity });

/** groups of equal circles (same radius within 1 µm) that are not generated by a feature */
function circleGroups(d: StudioDoc): { r: number; ids: string[] }[] {
  const g: { r: number; ids: string[] }[] = [];
  for (const e of d.ents) if (e.k === 'circle' && !e.feature && (!e.style || e.style === 'normal')) { const x = g.find((q) => Math.abs(q.r - e.r) < 1e-3); if (x) x.ids.push(e.id); else g.push({ r: e.r, ids: [e.id] }); }
  return g;
}
/** equal circles with centres on one circle at equal angles: a bolt circle (hole pattern) */
export function detectPattern(cs: EntOf<'circle'>[]): { c: Pt; pcd: number; n: number; start: number } | null {
  if (cs.length < 3) return null;
  const c: Pt = [cs.reduce((s, e) => s + e.c[0], 0) / cs.length, cs.reduce((s, e) => s + e.c[1], 0) / cs.length];
  const rs = cs.map((e) => dist(e.c, c)), R = rs.reduce((a, b) => a + b, 0) / rs.length;
  if (R < 1e-6 || rs.some((r) => Math.abs(r - R) > 1e-3 * Math.max(1, R))) return null;
  const angs = cs.map((e) => Math.atan2(e.c[1] - c[1], e.c[0] - c[0])).sort((a, b) => a - b);
  const step = (2 * Math.PI) / cs.length;
  for (let i = 0; i < angs.length; i++) { const gap = (i + 1 < angs.length ? angs[i + 1] : angs[0] + 2 * Math.PI) - angs[i]; if (Math.abs(gap - step) > 1e-3) return null; }
  return { c, pcd: 2 * R, n: cs.length, start: (angs[0] * 180) / Math.PI };
}

export function detectParams(d: StudioDoc): Param[] {
  const out: Param[] = [];
  // 1. outer profiles: overall sizes
  const fromFeature = new Set(d.ents.filter((e) => e.feature).map((e) => e.id));
  const profs = outerLoops(d).filter((p) => !p.outer.ids.some((x) => fromFeature.has(x)));
  profs.forEach(({ outer, holes }, k) => {
    const b = loopBox(outer), name = profs.length > 1 ? `Profile ${k + 1}` : 'Profile';
    if (outer.circle) out.push({ id: `od:${outer.ids[0]}`, group: name, label: 'Outer diameter', unit: 'mm', value: r6(outer.circle.r * 2), min: 0.01, max: 1e6, origin: 'measured', ents: outer.ids });
    else {
      out.push({ id: `ow:${outer.ids.join('+')}`, group: name, label: 'Overall length (X)', unit: 'mm', value: r6(b.x1 - b.x0), min: 0.01, max: 1e6, origin: 'measured', ents: outer.ids, hint: 'Holes and internal profiles keep their size; their positions scale with the outline.' });
      out.push({ id: `oh:${outer.ids.join('+')}`, group: name, label: 'Overall width (Y)', unit: 'mm', value: r6(b.y1 - b.y0), min: 0.01, max: 1e6, origin: 'measured', ents: outer.ids, hint: 'Holes and internal profiles keep their size; their positions scale with the outline.' });
    }
    if (holes.length) {
      const cx = (b.x0 + b.x1) / 2, cy = (b.y0 + b.y1) / 2;
      const bore = holes.filter((h) => h.circle && dist(h.circle.c, outer.circle?.c ?? [cx, cy]) < 1e-3 * Math.max(1, b.x1 - b.x0)).sort((p, q) => q.area - p.area)[0];
      if (bore?.circle) out.push({ id: `bore:${bore.ids[0]}`, group: name, label: 'Centre hole (bore) diameter', unit: 'mm', value: r6(bore.circle.r * 2), min: 0.01, max: 1e6, origin: 'measured', ents: bore.ids });
      const wall = outer.circle && bore?.circle ? outer.circle.r - bore.circle.r : null;
      if (wall !== null) out.push({ id: `wall:${outer.ids[0]}:${bore!.ids[0]}`, group: name, label: 'Wall thickness (radial)', unit: 'mm', value: r6(wall), min: 0.01, max: 1e6, origin: 'measured', ents: [...outer.ids, ...bore!.ids], hint: 'Changes the bore; the outer diameter stays.' });
    }
  });
  // 2. equal circles and hole patterns
  for (const g of circleGroups(d)) {
    const cs = g.ids.map((id) => findEnt(d, id) as EntOf<'circle'>);
    out.push({ id: `cd:${g.ids.join('+')}`, group: 'Holes and circles', label: g.ids.length > 1 ? `Diameter of ${g.ids.length} equal circles` : 'Circle diameter', unit: 'mm', value: r6(g.r * 2), min: 0.01, max: 1e6, origin: 'measured', ents: g.ids });
    const pat = detectPattern(cs);
    if (pat) {
      out.push({ id: `pcd:${g.ids.join('+')}`, group: 'Holes and circles', label: `Pitch circle diameter (${pat.n} holes)`, unit: 'mm', value: r6(pat.pcd), min: 0, max: 1e6, origin: 'measured', ents: g.ids });
      out.push({ id: `pn:${g.ids.join('+')}`, group: 'Holes and circles', label: 'Number of equally spaced holes', unit: 'count', value: pat.n, min: 1, max: 360, origin: 'measured', ents: g.ids, hint: 'The holes are re-spaced equally on the same pitch circle.' });
    }
  }
  // 3. arcs (radii) not made by features
  for (const e of d.ents) if (e.k === 'arc' && !e.feature && (!e.style || e.style === 'normal')) out.push({ id: `ar:${e.id}`, group: 'Radii', label: 'Arc radius', unit: 'mm', value: r6(e.r), min: 0.001, max: 1e6, origin: 'measured', ents: [e.id] });
  // 4. dimensions
  for (const e of d.ents) if (e.k === 'dim') {
    const v = dimValue(d, e); if (v === null) continue;
    out.push({ id: `dim:${e.id}`, group: 'Dimensions', label: `${e.drive !== undefined ? 'Driving' : 'Reference'} ${e.d.kind === 'angle' ? 'angle' : 'dimension'} ${dimLabel(d, e, (x) => String(+x.toFixed(3)))}`, unit: e.d.kind === 'angle' ? 'deg' : 'mm', value: r6(v), min: e.d.kind === 'angle' ? 0 : 0.001, max: e.d.kind === 'angle' ? 180 : 1e6, origin: 'dimension', ents: [e.id], hint: 'Typing a value makes this a driving dimension: the drawing changes to match it.' });
  }
  // 5. features
  for (const f of d.features) {
    const label = featureLabel(f);
    if (f.t === 'library') {
      const fam = getFamily(f.familyId);
      for (const fld of fam?.fields ?? []) if (fld.kind === 'number' && (!fld.showIf || fld.showIf({ ...fam!.defaults, ...f.params }))) {
        const v = f.params[fld.key]; if (typeof v !== 'number') continue;
        out.push({ id: `fv:${f.id}:${fld.key}`, group: label, label: fld.label + (fld.unit ? ` (${fld.unit})` : ''), unit: fld.unit === 'mm' ? 'mm' : fld.unit === '°' || fld.unit === 'deg' ? 'deg' : 'count', value: v, min: fld.min ?? -1e9, max: fld.max ?? 1e9, origin: 'library', ents: d.ents.filter((e) => e.feature === f.id).map((e) => e.id), ...(fld.help ? { hint: fld.help } : {}) });
      }
      continue;
    }
    for (const fld of FEATURE_FIELDS[f.t]) { const v = featureValue(f, fld.key); if (typeof v === 'number') out.push({ id: `fv:${f.id}:${fld.key}`, group: label, label: fld.label, unit: fld.unit === 'text' ? 'mm' : fld.unit, value: r6(v), min: fld.min, max: fld.max, origin: 'feature', ents: d.ents.filter((e) => e.feature === f.id).map((e) => e.id) }); }
  }
  // 6. bodies
  for (const b of d.bodies) {
    const g = `3D: ${b.name}`;
    if (b.op !== 'revolve') { out.push({ id: `bd:${b.id}:depth`, group: g, label: b.op === 'loft' ? 'Loft height' : b.mode === 'cut' ? 'Cut depth' : 'Thickness / extrude depth', unit: 'mm', value: b.depth, min: 0.001, max: 1e6, origin: 'body', ents: [b.profile] }); out.push({ id: `bd:${b.id}:z0`, group: g, label: 'Start height (Z)', unit: 'mm', value: b.z0, min: -1e6, max: 1e6, origin: 'body', ents: [b.profile] }); }
    else out.push({ id: `bd:${b.id}:angle`, group: g, label: 'Revolve angle', unit: 'deg', value: b.angle ?? 360, min: 1, max: 360, origin: 'body', ents: [b.profile] });
    for (const k of ['fillet', 'chamfer', 'shell'] as const) if (b[k]) out.push({ id: `bd:${b.id}:${k}`, group: g, label: k === 'fillet' ? 'Edge fillet radius' : k === 'chamfer' ? 'Edge chamfer' : 'Shell wall thickness', unit: 'mm', value: b[k]!, min: 0, max: 1e5, origin: 'body', ents: [b.profile] });
    if (b.pattern) out.push({ id: `bd:${b.id}:pn`, group: g, label: 'Pattern copies', unit: 'count', value: b.pattern.n, min: 1, max: 500, origin: 'body', ents: [b.profile] });
  }
  return out;
}

/** Applies a new value to a detected parameter. Nothing in the document is changed if it fails. */
export function applyParam(d: StudioDoc, id: string, v: number): ApplyResult {
  if (!Number.isFinite(v)) return { ok: false, error: 'Enter a number.' };
  const p = detectParams(d).find((x) => x.id === id);
  if (!p) return { ok: false, error: 'This value no longer exists (the drawing changed). Pick it again.' };
  if (v < p.min - 1e-12 || v > p.max + 1e-12) return { ok: false, error: `${p.label}: allowed ${p.min} to ${p.max}.` };
  if (p.unit === 'count' && !Number.isInteger(v)) return { ok: false, error: `${p.label}: enter a whole number.` };
  const [kind, ...rest] = id.split(':');
  const ids = (rest[0] ?? '').split('+');
  const mapEnts = (f: (e: Ent) => Ent) => ({ ...d, ents: d.ents.map(f) });
  const resolve = (doc: StudioDoc, note?: string): ApplyResult => { const s = solve(doc); return s.ok ? { ok: true, doc: s.doc, note } : { ok: false, error: s.error ?? 'Could not apply.' }; };
  switch (kind) {
    case 'od': return resolve(mapEnts((e) => (e.id === ids[0] && e.k === 'circle' ? { ...e, r: v / 2 } : e)));
    case 'cd': case 'bore': return resolve(mapEnts((e) => (ids.includes(e.id) && (e.k === 'circle' || e.k === 'arc') ? { ...e, r: v / 2 } : e)));
    case 'wall': { const outer = findEnt(d, ids[0]); const bid = rest[1]; if (outer?.k !== 'circle') return { ok: false, error: 'Outer circle not found.' }; if (v >= outer.r) return { ok: false, error: `The wall (${v} mm) must be less than the outer radius (${+outer.r.toFixed(3)} mm).` }; return resolve(mapEnts((e) => (e.id === bid && e.k === 'circle' ? { ...e, r: outer.r - v } : e))); }
    case 'ar': return resolve(mapEnts((e) => (e.id === ids[0] && e.k === 'arc' ? { ...e, r: v } : e)));
    case 'ow': case 'oh': {
      const loopIds = new Set(ids), outerEnts = d.ents.filter((e) => loopIds.has(e.id));
      const b = boxOf(outerEnts), cur = kind === 'ow' ? b.x1 - b.x0 : b.y1 - b.y0;
      if (cur < 1e-9) return { ok: false, error: 'This outline has no size in that direction.' };
      const k = v / cur, anchor: Pt = [(b.x0 + b.x1) / 2, (b.y0 + b.y1) / 2];
      const m = kind === 'ow' ? scaleAff(anchor, k, 1) : scaleAff(anchor, 1, k);
      // holes and internal profiles inside the outline: keep their size, move their centre
      const { loops } = findLoops(d), outer = loops.find((l) => l.ids.some((x) => loopIds.has(x)));
      const inner = new Set(outer ? loops.filter((l) => l !== outer && loopInside(l, outer)).flatMap((l) => l.ids) : []);
      const next = mapEnts((e) => {
        if (loopIds.has(e.id)) return transformEnt(e, m);
        if (inner.has(e.id)) { const bb = entBox(e), c: Pt = [(bb.x0 + bb.x1) / 2, (bb.y0 + bb.y1) / 2], c2 = applyAff(m, c); return transformEnt(e, translateAff(c2[0] - c[0], c2[1] - c[1])); }
        return e;
      });
      // features inside the outline move with it
      const feats = next.features.map((f) => moveFeature(f, (q) => applyAff(m, q), inner, d));
      let doc: StudioDoc = { ...next, features: feats };
      for (const f of feats) if (f !== d.features.find((x) => x.id === f.id)) { const r = regenerate(doc, f); if (r.error) return { ok: false, error: r.error }; doc = r.doc; }
      return resolve(doc, 'Holes kept their size; their positions were scaled with the outline.');
    }
    case 'pcd': case 'pn': {
      const cs = ids.map((x) => findEnt(d, x)).filter((e): e is EntOf<'circle'> => e?.k === 'circle');
      const pat = detectPattern(cs); if (!pat) return { ok: false, error: 'These holes are no longer equally spaced on one circle.' };
      const n = kind === 'pn' ? v : pat.n, pcd = kind === 'pcd' ? v : pat.pcd, r = cs[0].r;
      if (n > 1 && (Math.PI * pcd) / n <= 2 * r) return { ok: false, error: `${n} holes of Ø${+(2 * r).toFixed(3)} would overlap on PCD ${pcd}.` };
      const keep = cs[0];
      const fresh: Ent[] = Array.from({ length: n }, (_, i) => ({ ...keep, id: i < cs.length ? cs[i].id : uid(), c: polarPt(pat.c, pcd / 2, ((pat.start + (360 * i) / n) * Math.PI) / 180) }));
      const gone = new Set(cs.slice(n).map((e) => e.id));
      const ents = [...d.ents.filter((e) => !ids.includes(e.id)), ...fresh];
      return resolve({ ...d, ents, constraints: d.constraints.filter((c) => !JSON.stringify(c).split('"').some((s) => gone.has(s))) });
    }
    case 'dim': {
      const e = findEnt(d, ids[0]); if (e?.k !== 'dim') return { ok: false, error: 'Dimension not found.' };
      return resolve(mapEnts((x) => (x.id === e.id ? { ...x, drive: v } : x)));
    }
    case 'fv': {
      const f = d.features.find((x) => x.id === rest[0]); if (!f) return { ok: false, error: 'Feature not found.' };
      const nf = setFeatureValue(f, rest[1], v); if ('error' in nf) return { ok: false, error: nf.error };
      const r = regenerate(d, nf); if (r.error) return { ok: false, error: r.error };
      return resolve(r.doc);
    }
    case 'bd': {
      const b = d.bodies.find((x) => x.id === rest[0]); if (!b) return { ok: false, error: '3D body not found.' };
      const key = rest[1];
      const nb: Body = key === 'pn' && b.pattern ? { ...b, pattern: { ...b.pattern, n: v } } : { ...b, [key]: v };
      return { ok: true, doc: { ...d, bodies: d.bodies.map((x) => (x.id === b.id ? nb : x)) } };
    }
  }
  return { ok: false, error: 'This value cannot be edited.' };
}
function moveFeature(f: Feature, T: (p: Pt) => Pt, inner: Set<string>, d: StudioDoc): Feature {
  const mine = d.ents.filter((e) => e.feature === f.id).map((e) => e.id);
  if (!mine.length || !mine.every((x) => inner.has(x))) return f;
  if (f.t === 'gridHoles') { const p = T([f.x0, f.y0]); return { ...f, x0: p[0], y0: p[1] }; }
  if (f.t === 'library') return { ...f, at: T(f.at) };
  return { ...f, c: T(f.c) } as Feature;
}

/** Scales the selection (or everything) independently in X and Y. With keepHoles, circles keep their size and only move. */
export function scaleXY(d: StudioDoc, ids: string[] | null, sx: number, sy: number, keepHoles: boolean): ApplyResult {
  if (!(sx > 0) || !(sy > 0) || sx > 1e4 || sy > 1e4) return { ok: false, error: 'Scale factors must be between 0 and 10 000 (1 = no change).' };
  const sel = new Set(ids ?? d.ents.map((e) => e.id));
  const b = boxOf(d.ents.filter((e) => sel.has(e.id))), c: Pt = [(b.x0 + b.x1) / 2, (b.y0 + b.y1) / 2];
  if (!Number.isFinite(c[0])) return { ok: false, error: 'Nothing to scale.' };
  const m = scaleAff(c, sx, sy);
  const ents = d.ents.map((e) => {
    if (!sel.has(e.id) || e.k === 'dim') return e;
    if (keepHoles && e.k === 'circle') { const c2 = applyAff(m, e.c); return { ...e, c: c2 }; }
    return transformEnt(e, m);
  });
  const note = !keepHoles && Math.abs(sx - sy) > 1e-12 && d.ents.some((e) => sel.has(e.id) && e.k === 'circle') ? 'Circles scaled by different X and Y factors became ellipses.' : undefined;
  return { ok: true, doc: { ...d, ents }, note };
}
