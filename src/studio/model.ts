import type { Pt } from '../core/types.ts';

/* Design Studio document model.
 * All coordinates are stored in MILLIMETRES (the display unit is only a view setting), with Y pointing UP like a CAD sketch.
 * Every entity remembers where it came from (drawn, imported, traced, AI, library, feature) and whether a person has confirmed it,
 * so the studio can always show which values are measured, detected, corrected or assumed. */

export type Unit = 'mm' | 'cm' | 'm' | 'in';
export type Source = 'drawn' | 'imported' | 'traced' | 'ai' | 'library' | 'feature';

/** A point of an entity: index i of its handle list (see `handles` in geom.ts). */
export interface PRef { e: string; i: number }
/** A straight edge: a line entity, or one segment of a polyline (seg = index of its first vertex). */
export interface LRef { e: string; seg?: number }

export type Shape =
  | { k: 'line'; a: Pt; b: Pt }
  /** polyline, rectangle, polygon or freehand stroke. bulge[i] (optional) bends segment i -> i+1 into an arc: bulge = tan(arc angle / 4), like DXF. */
  | { k: 'poly'; pts: Pt[]; closed: boolean; bulge?: number[] }
  | { k: 'circle'; c: Pt; r: number }
  /** arc from angle a0 to a1 (radians), counter-clockwise */
  | { k: 'arc'; c: Pt; r: number; a0: number; a1: number }
  | { k: 'ellipse'; c: Pt; rx: number; ry: number; rot: number }
  /** smooth curve through the given points (centripetal Catmull-Rom) */
  | { k: 'spline'; pts: Pt[]; closed: boolean }
  | { k: 'text'; p: Pt; s: string; h: number; arrowTo?: Pt }
  | { k: 'dim'; d: Dim };

export type Dim =
  | { kind: 'dist' | 'hdist' | 'vdist'; p1: PRef; p2: PRef; off: number }
  | { kind: 'length'; l: LRef; off: number }
  | { kind: 'radius' | 'diameter'; e: string; ang: number }
  | { kind: 'angle'; l1: LRef; l2: LRef; rad: number };

export interface EntBase {
  id: string; layer: string; source: Source;
  /** construction / centre lines are drawn dashed and never become part of a 3D profile */
  style?: 'normal' | 'construction' | 'centre';
  /** values from tracing / AI / imports are unconfirmed until a person ticks them */
  confirmed?: boolean;
  /** generated by a parametric feature: editing the feature regenerates these */
  feature?: string;
  /** dimensions only: when set, the dimension DRIVES the geometry (the solver keeps it at this value, mm or degrees) */
  drive?: number;
  /** traced items: the reference picture they were traced from (they follow its scale calibration) */
  refId?: string;
}
export type Ent = EntBase & Shape;
export type EntOf<K extends Shape['k']> = EntBase & Extract<Shape, { k: K }>;

export type Constraint =
  | { id: string; t: 'horizontal' | 'vertical'; l: LRef }
  | { id: string; t: 'parallel' | 'perpendicular' | 'equal'; l1: LRef; l2: LRef }
  | { id: string; t: 'equalRadius' | 'concentric'; e1: string; e2: string }
  | { id: string; t: 'tangent'; l: LRef; e: string }
  | { id: string; t: 'coincident'; p1: PRef; p2: PRef }
  | { id: string; t: 'symmetric'; p1: PRef; p2: PRef; axis: LRef }
  | { id: string; t: 'fix'; e: string };

export interface Layer { id: string; name: string; visible: boolean; locked: boolean; color: string }

/** Parametric 2D features: their entities are regenerated from these values. */
export type Feature =
  | { id: string; t: 'holePattern'; c: Pt; pcd: number; n: number; d: number; start: number }
  | { id: string; t: 'gridHoles'; x0: number; y0: number; nx: number; ny: number; dx: number; dy: number; d: number }
  | { id: string; t: 'slot'; c: Pt; len: number; w: number; ang: number }
  | { id: string; t: 'polygon'; c: Pt; n: number; r: number; ang: number }
  | { id: string; t: 'library'; familyId: string; params: Record<string, number | string | boolean>; at: Pt; label: string; view: 'top' | 'side' };

/** 3D bodies made from closed profiles of the sketch. */
export type BodyOp = 'extrude' | 'revolve' | 'loft';
export interface Body {
  id: string; name: string; op: BodyOp;
  /** entity id of the OUTER profile; every closed profile inside it becomes a hole / internal profile */
  profile: string;
  /** extrude/loft: start height and depth along Z (mm). revolve: unused */
  z0: number; depth: number;
  /** revolve: axis in the sketch ('y' = the vertical line x = axisAt, 'x' = horizontal line y = axisAt) and angle in degrees */
  axis?: 'x' | 'y'; axisAt?: number; angle?: number;
  /** loft: second profile (placed at z0 + depth) */
  profile2?: string;
  /** how this body combines with the bodies before it */
  mode: 'new' | 'add' | 'cut' | 'intersect';
  /** cut bodies: which body they cut (default: the first body below) */
  target?: string;
  /** exact-kernel finishing operations (OpenCascade): all edges */
  fillet?: number; chamfer?: number; shell?: number;
  /** pattern of this body: n copies around the Z axis or along X */
  pattern?: { kind: 'circular'; n: number } | { kind: 'linear'; n: number; dx: number; dy: number };
  material: string; color: string; visible: boolean;
}

/** The original uploaded picture/PDF page, kept as a locked reference layer (never edited, never overwritten). */
export interface Reference {
  id: string; name: string; mime: string; kind: 'image' | 'pdf' | 'svg' | 'dxf';
  /** downscaled copy for display (data URL); the full original can be stored in the cloud as an upload */
  dataUrl: string; uploadId?: string; pxW: number; pxH: number;
  /** placement in the sketch: lower-left corner (mm), mm per pixel, rotation (deg) */
  x: number; y: number; mmPerPx: number; rot: number;
  /** true once a person has set the scale from a known distance */
  calibrated: boolean; opacity: number; visible: boolean;
  /** text / dimensions read from the drawing (PDF text or AI), in pixel coordinates of the page */
  detected: Detected[];
}
export interface Detected {
  id: string; text: string; value: number | null; unit: string;
  kind: 'length' | 'diameter' | 'radius' | 'angle' | 'count' | 'thread' | 'note';
  /** pixel position on the reference */
  px: number; py: number;
  from: 'pdf-text' | 'ai';
  confidence: number;
  /** entity / dimension it was matched to by the person */
  appliedTo?: string;
  status: 'detected' | 'confirmed' | 'rejected';
}

export interface Version { id: string; label: string; at: string; by: string; snapshot: string }
export interface AiNote { id: string; at: string; prompt: string; reply: string; applied: string[]; rejected: string[] }

export interface StudioDoc {
  format: 'ultraplast-studio'; formatVersion: 1;
  id: string; name: string; componentType: string; material: string;
  version: number; revision: string;
  createdAt: string; updatedAt: string; createdBy: string;
  unit: Unit;
  layers: Layer[]; ents: Ent[]; constraints: Constraint[]; features: Feature[]; bodies: Body[];
  refs: Reference[];
  notes: string[];
  /** manual versions (snapshots without pictures), newest last */
  versions: Version[];
  ai: AiNote[];
}

export const STUDIO_FORMAT = 'ultraplast-studio';
export const STUDIO_FAMILY = 'studio';

let counter = 0;
export const uid = (p = 'e'): string => `${p}${Date.now().toString(36)}${(counter++).toString(36)}${Math.random().toString(36).slice(2, 5)}`;

export const DEFAULT_LAYERS: Layer[] = [
  { id: 'L0', name: 'Geometry', visible: true, locked: false, color: '#0f172a' },
  { id: 'L1', name: 'Construction', visible: true, locked: false, color: '#64748b' },
  { id: 'L2', name: 'Dimensions', visible: true, locked: false, color: '#0e7490' },
  { id: 'L3', name: 'Notes', visible: true, locked: false, color: '#7c3aed' },
  { id: 'L4', name: 'Imported / traced', visible: true, locked: false, color: '#b45309' },
];

export function newDoc(name = 'New design', by = ''): StudioDoc {
  const now = new Date().toISOString();
  return {
    format: STUDIO_FORMAT, formatVersion: 1, id: uid('s_'), name, componentType: 'Custom component', material: 'S235 Steel',
    version: 1, revision: 'A', createdAt: now, updatedAt: now, createdBy: by, unit: 'mm',
    layers: DEFAULT_LAYERS.map((l) => ({ ...l })), ents: [], constraints: [], features: [], bodies: [], refs: [], notes: [], versions: [], ai: [],
  };
}

/* ---------- units ---------- */
export const UNIT_MM: Record<Unit, number> = { mm: 1, cm: 10, m: 1000, in: 25.4 };
export const toUnit = (mm: number, u: Unit): number => mm / UNIT_MM[u];
export const fromUnit = (v: number, u: Unit): number => v * UNIT_MM[u];
export function fmtLen(mm: number, u: Unit, dp = 3): string {
  if (!Number.isFinite(mm)) return '-';
  const v = toUnit(mm, u), d = u === 'in' ? Math.max(dp, 4) : u === 'm' ? Math.max(dp, 5) : dp;
  return `${+v.toFixed(d)}`;
}
/** Reads a length typed by a person: "25", "25.4 mm", "2.5cm", "1 in", '1"', "0.3 m". Plain numbers are in the current unit. */
export function parseLen(text: string, u: Unit): number | null {
  const m = String(text).trim().replace(',', '.').match(/^([-+]?\d*\.?\d+(?:e[-+]?\d+)?)\s*(mm|cm|m|in|inch|inches|")?$/i);
  if (!m) return null;
  const v = Number(m[1]); if (!Number.isFinite(v)) return null;
  const unit = (m[2] ?? '').toLowerCase();
  const k = unit === 'mm' ? 1 : unit === 'cm' ? 10 : unit === 'm' ? 1000 : unit === 'in' || unit === 'inch' || unit === 'inches' || unit === '"' ? 25.4 : UNIT_MM[u];
  return v * k;
}
export function parseAngle(text: string): number | null {
  const m = String(text).trim().replace(',', '.').match(/^([-+]?\d*\.?\d+)\s*(°|deg|degrees?|rad)?$/i);
  if (!m) return null;
  const v = Number(m[1]);
  return Number.isFinite(v) ? (m[2]?.toLowerCase() === 'rad' ? (v * 180) / Math.PI : v) : null;
}

/* ---------- serialisation ---------- */
export function serializeDoc(d: StudioDoc): string {
  return JSON.stringify(d, (_k, v) => (typeof v === 'number' && !Number.isFinite(v) ? null : v));
}
const isPt = (p: unknown): p is Pt => Array.isArray(p) && p.length === 2 && p.every((n) => typeof n === 'number' && Number.isFinite(n) && Math.abs(n) < 1e7);
const fin = (n: unknown, lo = -1e7, hi = 1e7): n is number => typeof n === 'number' && Number.isFinite(n) && n >= lo && n <= hi;

/** Checks one entity read from a file. Returns null for anything broken, so a damaged file never crashes the studio. */
export function cleanEnt(e: unknown): Ent | null {
  if (!e || typeof e !== 'object') return null;
  const x = e as Record<string, unknown>;
  if (typeof x.id !== 'string' || typeof x.layer !== 'string') return null;
  const base: EntBase = { id: x.id.slice(0, 64), layer: x.layer.slice(0, 64), source: (['drawn', 'imported', 'traced', 'ai', 'library', 'feature'] as Source[]).includes(x.source as Source) ? (x.source as Source) : 'drawn' };
  if (x.style === 'construction' || x.style === 'centre') base.style = x.style;
  if (typeof x.confirmed === 'boolean') base.confirmed = x.confirmed;
  if (typeof x.feature === 'string') base.feature = x.feature;
  if (fin(x.drive)) base.drive = x.drive;
  if (typeof x.refId === 'string') base.refId = x.refId.slice(0, 64);
  switch (x.k) {
    case 'line': return isPt(x.a) && isPt(x.b) ? { ...base, k: 'line', a: x.a, b: x.b } : null;
    case 'poly': {
      if (!Array.isArray(x.pts) || x.pts.length < 2 || x.pts.length > 20000 || !x.pts.every(isPt)) return null;
      const bulge = Array.isArray(x.bulge) && x.bulge.every((b) => fin(b, -1e3, 1e3)) ? (x.bulge as number[]).slice(0, x.pts.length) : undefined;
      return { ...base, k: 'poly', pts: x.pts as Pt[], closed: !!x.closed, ...(bulge && bulge.some((b) => b !== 0) ? { bulge } : {}) };
    }
    case 'circle': return isPt(x.c) && fin(x.r, 1e-6) ? { ...base, k: 'circle', c: x.c, r: x.r } : null;
    case 'arc': return isPt(x.c) && fin(x.r, 1e-6) && fin(x.a0) && fin(x.a1) ? { ...base, k: 'arc', c: x.c, r: x.r, a0: x.a0, a1: x.a1 } : null;
    case 'ellipse': return isPt(x.c) && fin(x.rx, 1e-6) && fin(x.ry, 1e-6) && fin(x.rot) ? { ...base, k: 'ellipse', c: x.c, rx: x.rx, ry: x.ry, rot: x.rot } : null;
    case 'spline': return Array.isArray(x.pts) && x.pts.length >= 2 && x.pts.length <= 5000 && x.pts.every(isPt) ? { ...base, k: 'spline', pts: x.pts as Pt[], closed: !!x.closed } : null;
    case 'text': return isPt(x.p) && typeof x.s === 'string' && fin(x.h, 0.01, 1e4) ? { ...base, k: 'text', p: x.p, s: x.s.slice(0, 500), h: x.h, ...(isPt(x.arrowTo) ? { arrowTo: x.arrowTo } : {}) } : null;
    case 'dim': return x.d && typeof x.d === 'object' && typeof (x.d as { kind?: unknown }).kind === 'string' ? { ...base, k: 'dim', d: x.d as Dim } : null;
    default: return null;
  }
}

/** Reads a studio file (JSON). Throws a readable Error. Unknown or damaged parts are dropped and listed in `dropped`. */
export function parseDoc(text: string): { doc: StudioDoc; dropped: number } {
  let raw: Record<string, unknown>;
  try { raw = JSON.parse(text) as Record<string, unknown>; } catch { throw new Error('The file is not valid JSON.'); }
  if (!raw || raw.format !== STUDIO_FORMAT) throw new Error('This is not an Ultraplast Design Studio file.');
  if (raw.formatVersion !== 1) throw new Error(`Unsupported studio file version: ${String(raw.formatVersion)}.`);
  const base = newDoc();
  const ents0 = Array.isArray(raw.ents) ? raw.ents : [];
  const ents = ents0.map(cleanEnt).filter((e): e is Ent => !!e);
  const str = (v: unknown, d: string, max = 200) => (typeof v === 'string' ? v.slice(0, max) : d);
  const arr = <T>(v: unknown): T[] => (Array.isArray(v) ? (v as T[]) : []);
  const doc: StudioDoc = {
    ...base,
    id: typeof raw.id === 'string' && /^[\w-]{1,64}$/.test(raw.id) ? raw.id : base.id,
    name: str(raw.name, base.name, 120), componentType: str(raw.componentType, base.componentType), material: str(raw.material, base.material),
    version: fin(raw.version, 1, 1e6) ? Math.round(raw.version) : 1, revision: str(raw.revision, 'A', 8),
    createdAt: str(raw.createdAt, base.createdAt), updatedAt: str(raw.updatedAt, base.updatedAt), createdBy: str(raw.createdBy, ''),
    unit: (['mm', 'cm', 'm', 'in'] as Unit[]).includes(raw.unit as Unit) ? (raw.unit as Unit) : 'mm',
    layers: arr<Layer>(raw.layers).filter((l) => l && typeof l.id === 'string' && typeof l.name === 'string').map((l) => ({ id: l.id, name: l.name.slice(0, 60), visible: l.visible !== false, locked: !!l.locked, color: typeof l.color === 'string' ? l.color : '#0f172a' })),
    ents,
    constraints: arr<Constraint>(raw.constraints).filter((c) => c && typeof c.id === 'string' && typeof c.t === 'string'),
    features: arr<Feature>(raw.features).filter((f) => f && typeof f.id === 'string' && typeof f.t === 'string'),
    bodies: arr<Body>(raw.bodies).filter((b) => b && typeof b.id === 'string' && typeof b.profile === 'string' && fin(b.depth) && fin(b.z0)),
    refs: arr<Reference>(raw.refs).filter((r) => r && typeof r.id === 'string' && typeof r.dataUrl === 'string' && fin(r.mmPerPx, 1e-9)),
    notes: arr<string>(raw.notes).filter((n) => typeof n === 'string').slice(0, 100),
    versions: arr<Version>(raw.versions).filter((v) => v && typeof v.snapshot === 'string').slice(-30),
    ai: arr<AiNote>(raw.ai).filter((a) => a && typeof a.prompt === 'string').slice(-100),
  };
  if (!doc.layers.length) doc.layers = DEFAULT_LAYERS.map((l) => ({ ...l }));
  for (const e of doc.ents) if (!doc.layers.some((l) => l.id === e.layer)) e.layer = doc.layers[0].id;
  return { doc, dropped: ents0.length - ents.length };
}
